#!/usr/bin/env python3
"""Build the playable demo's assets from the game repository.

Everything the demo shows or plays comes from the game itself:

- play/pipes.webp   the pipe tiles the PC port ships (godot/assets/pipes/, drawn by
                    godot/tools/pipe_art_factory.py, the Pillow port of iOS
                    PipeArtFactory.swift), packed into one 8 x 8 atlas:
                    column = tile kind (PipeTile order), row = rotation * 2 + wet.
- play/levels.js    three campaign boards, scrambled exactly as the game scrambles
                    them (godot/tools/reference_model.py, which the Godot and Swift
                    suites check against each other), plus each level's pressure
                    numbers from PressureProfile.
- play/audio/*.mp3  the game's own CC0 cues and music (godot/assets/audio/).
- play/props/*.webp underwater props and challenge emblems from the game's asset catalog.

usage: python3 tools/build_demo_assets.py [--game "~/projects/Pipe Flow/PlumberPuzzle"]
Needs Pillow and ffmpeg. Rerun after the game's art, audio or levels change.
"""
from __future__ import annotations

import argparse
import json
import math
import subprocess
import sys
from pathlib import Path

from PIL import Image

SITE = Path(__file__).resolve().parent.parent
OUT = SITE / "play"
KINDS = ["empty", "straight", "corner", "tee", "cross", "source", "drain", "bridge"]
CELL = 128

# The three free stages: teach, add the clock, the peak. Level ids from the game.
STAGES = [
    {"id": 1, "clock": False},   # First Drop: rotate a single run, no clock
    {"id": 7, "clock": True},    # Pressure: the water releases on a timer
    {"id": 29, "clock": True},   # Pressure Web: tees around a fixed cross lattice
]
# PLAYABLE-DEMO.md: soften the game's numbers for a first-time player.
GRACE_SOFTEN = 1.5
AUDIO = ["sfx_rotate", "sfx_invalid", "sfx_leak", "sfx_level_clear", "sfx_surge",
         "sfx_tile_fill", "sfx_lock_in", "sfx_warning", "water_flow_loop", "music_underwater"]
PROPS = ["PropFishBlue", "PropFishYellow", "PropFishClown", "PropLightRayWide", "PropLightRayTall"]
# The four challenge-mode emblems, shown locked on the demo's last card.
EMBLEMS = ["EmblemChallengeRapidFlow", "EmblemChallengePerfectSeal", "EmblemChallengeDailyDive",
           "EmblemChallengeEndlessDescent"]


def pressure(level_id: int, par: int, width: int, height: int) -> dict:
    """PressureProfile (godot/scripts/pressure_profile.gd) for the standard campaign."""
    t = max(0, level_id - 1) / 79
    complexity_allowance = min(2.4, max(0.0, width * height / 63) * 1.6)
    planning = (8.0 - t * 2.6) + par * (0.34 - t * 0.02) + complexity_allowance
    grace = max(2.2, max(5.0, planning * (1.0 - t * 0.18)))
    return {
        "grace": round(grace, 2),
        "travel": round(max(0.20, max(0.32, 0.72 - t * 0.35)), 3),
        "leakGraceFraction": round(0.42 - t * 0.12, 3),
        "leakCooldown": round(max(1.35, 2.5 - t * 0.75), 2),
        "rampPerSecond": round(0.03 + t * 0.05, 4),
    }


def build_levels(game: Path) -> None:
    sys.path.insert(0, str(game / "godot" / "tools"))
    import reference_model as rm  # noqa: E402  (the game's own model)

    levels = {lv.id: lv for lv in rm.load_levels()}
    out = []
    for stage in STAGES:
        lv = levels[stage["id"]]
        canon, start = lv.make_canonical(), lv.make_board()
        p = pressure(lv.id, lv.par, start.width, start.height)
        out.append({
            "id": lv.id, "name": lv.name, "par": lv.par, "w": start.width, "h": start.height,
            "kinds": rm.kind_string(start), "start": rm.rot_string(start),
            "solved": rm.rot_string(canon), "clock": stage["clock"],
            "grace": round(p["grace"] * GRACE_SOFTEN, 1), "gameGrace": p["grace"],
            "travel": p["travel"], "leakGraceFraction": p["leakGraceFraction"],
            "leakCooldown": p["leakCooldown"], "rampPerSecond": p["rampPerSecond"],
        })
    body = json.dumps(out, separators=(",", ":"))
    (OUT / "levels.js").write_text(
        "/* Generated by tools/build_demo_assets.py from the game's levels.json. Do not edit. */\n"
        f"window.PP_LEVELS = {body};\n")
    for s in out:
        print(f"  level {s['id']:>3} {s['name']:<14} {s['w']}x{s['h']} par {s['par']:>3}"
              f"  grace {s['gameGrace']}s -> {s['grace']}s")


def build_atlas(game: Path) -> None:
    pipes = game / "godot" / "assets" / "pipes"
    atlas = Image.new("RGBA", (CELL * len(KINDS), CELL * 8), (0, 0, 0, 0))
    for col, kind in enumerate(KINDS):
        for rot in range(4):
            for wet, state in enumerate(("dry", "wet")):
                tile = Image.open(pipes / f"{kind}_r{rot}_{state}.png").convert("RGBA")
                atlas.paste(tile.resize((CELL, CELL), Image.LANCZOS), (col * CELL, (rot * 2 + wet) * CELL))
    atlas.save(OUT / "pipes.webp", "WEBP", quality=88, method=6)


def build_audio(game: Path) -> None:
    src, dst = game / "godot" / "assets" / "audio", OUT / "audio"
    dst.mkdir(exist_ok=True)
    for name in AUDIO:
        rate = "96k" if name.startswith("music") else "80k"
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(src / f"{name}.ogg"),
                        "-ac", "2" if name.startswith("music") else "1", "-b:a", rate,
                        str(dst / f"{name}.mp3")], check=True)


def build_props(game: Path) -> None:
    assets, dst = game / "godot" / "assets", OUT / "props"
    dst.mkdir(exist_ok=True)
    for name, src, size in [(n, assets / "props", 320) for n in PROPS] + [(n, assets / "ui", 112) for n in EMBLEMS]:
        im = Image.open(src / f"{name}.png").convert("RGBA")
        scale = min(1.0, size / max(im.size))
        im = im.resize((math.ceil(im.width * scale), math.ceil(im.height * scale)), Image.LANCZOS)
        im.save(dst / f"{name}.webp", "WEBP", quality=82, method=6)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--game", default="~/projects/Pipe Flow/PlumberPuzzle")
    game = Path(ap.parse_args().game).expanduser()
    if not (game / "godot" / "tools" / "reference_model.py").exists():
        sys.exit(f"not the Plumber Puzzle repo: {game}")
    OUT.mkdir(exist_ok=True)
    build_levels(game)
    build_atlas(game)
    build_audio(game)
    build_props(game)
    total = sum(f.stat().st_size for f in OUT.rglob("*") if f.is_file())
    print(f"wrote {OUT} ({total / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
